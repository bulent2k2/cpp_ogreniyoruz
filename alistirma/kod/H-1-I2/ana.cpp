// H-1-I2 · Bölme üç türlü
// Çalıştırın, sonra 7'leri 9 yapın.
#include <iostream>
using namespace std;

int main() {
  cout << "7 / 2 = "   << 7 / 2   << endl;   // tam bölme
  cout << "7 % 2 = "   << 7 % 2   << endl;   // kalan
  cout << "7.0 / 2 = " << 7.0 / 2 << endl;   // kesirli bölme
  return 0;
}
